import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:intragram/core/image_header.dart';

void main() {
  test('probes PNG, GIF, JPEG, WebP, and BMP dimensions without decoding', () {
    final png = Uint8List.fromList([
      0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, //
      0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
      0x00, 0x00, 0x01, 0x40, 0x00, 0x00, 0x00, 0xF0,
    ]);
    expect(probeEncodedImageDimensions(png), (width: 320, height: 240));

    final gif = Uint8List.fromList([
      0x47, 0x49, 0x46, 0x38, 0x39, 0x61, 0x40, 0x00, 0x30, 0x00, //
    ]);
    expect(probeEncodedImageDimensions(gif), (width: 64, height: 48));

    final jpeg = Uint8List.fromList([
      0xFF, 0xD8, // SOI
      0xFF, 0xE0, 0x00, 0x04, 0x11, 0x22, // APP0
      0xFF, 0xC0, 0x00, 0x0B, 0x08, 0x01, 0xE0, 0x02, 0x80, 0x01, 0x01, 0x11, 0,
    ]);
    expect(probeEncodedImageDimensions(jpeg), (width: 640, height: 480));

    final webpVp8x = Uint8List.fromList([
      0x52, 0x49, 0x46, 0x46, 0x20, 0x00, 0x00, 0x00, // RIFF
      0x57, 0x45, 0x42, 0x50, 0x56, 0x50, 0x38, 0x58, // WEBPVP8X
      0x0A, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0xFF, 0x03, 0x00, 0xFF, 0x02, 0x00,
    ]);
    expect(probeEncodedImageDimensions(webpVp8x), (width: 1024, height: 768));

    final bmp = Uint8List(26)
      ..[0] = 0x42
      ..[1] = 0x4D
      ..[14] = 40
      ..[18] = 128
      ..[22] = 0xA0
      ..[23] = 0xFF
      ..[24] = 0xFF
      ..[25] = 0xFF; // top-down -96
    expect(probeEncodedImageDimensions(bmp), (width: 128, height: 96));

    expect(probeEncodedImageDimensions(Uint8List.fromList([1, 2, 3])), isNull);
  });
}
