import assert from 'node:assert/strict';
import { createInterface } from 'node:readline';
import { webcrypto } from 'node:crypto';
import { WebPeerEvidence, validateEvidenceControl } from '../docs/web/evidence.mjs';
import { b64 } from '../docs/web/evidence-wire.mjs';
globalThis.crypto ||= webcrypto;
const lines = createInterface({ input: process.stdin })[Symbol.asyncIterator]();
const init = JSON.parse((await lines.next()).value);
const sent = [];
const evidence = new WebPeerEvidence({ sendControl: async c => { validateEvidenceControl(c); sent.push(c); } });
await evidence.start(init.binding, { dialled: false });
process.stdout.write(JSON.stringify({ identity: sent[0], publicKey: evidence.publicKey, peerId: evidence.peerId }) + '\n');
const native = JSON.parse((await lines.next()).value);
await evidence.receive(native.identity);
assert.equal(evidence.peerIdentity.peerId, native.peerId);
await evidence.expectFile(native.receipt.value.s, Uint8Array.from(Buffer.from(native.bytes, 'base64')));
await evidence.receive(native.receipt);
assert.equal(evidence.entries[0].status, 'verified');
const count = evidence.entries.length;
const altered = structuredClone(native.receipt); altered.value.o = 'altered';
await evidence.receive(altered);
assert.equal(evidence.entries.length, count);
assert.equal(await evidence.importBundle(native.bundle), true);
const tampered = JSON.parse(native.bundle); tampered.entries[0].salt = b64(new Uint8Array(16));
assert.equal(await evidence.importBundle(JSON.stringify(tampered)), false);
await evidence.setTrustBundle(native.trust);
await evidence.setCredential(native.browserCredential);
await evidence.receive(native.organization);
assert.equal(evidence.organization.verified, true);
assert.equal(evidence.organization.demo, true);
const replay = new WebPeerEvidence({ sendControl: async () => {} });
await replay.start(init.binding2, { dialled: false });
await replay.receive(native.identity);
await replay.receive(native.receipt);
assert.equal(replay.peerIdentity, null); assert.equal(replay.entries.length, 0);
await evidence.recordFile(native.outgoingId, Uint8Array.from(Buffer.from(native.bytes, 'base64')));
const bundle = await evidence.exportBundle();
assert.equal(await evidence.importBundle(bundle), true);
const witness = await replay.witnessBundle(bundle);
assert.equal(await evidence.attachAnchor(witness, replay.peerId), true);
assert.equal(await evidence.importBundle(JSON.stringify(evidence.lastBundle)), true);
process.stdout.write(JSON.stringify({ receipt: sent.find(c => c.k === 'attestation'),
  organization: sent.find(c => c.k === 'org-credential'), bundle: JSON.stringify(evidence.lastBundle),
  signed: evidence.entries.length, organizationCheck: evidence.organization.check }) + '\n');
evidence.clear(); replay.clear();
process.exitCode = 0;
process.stdin.destroy();
