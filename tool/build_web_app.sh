#!/usr/bin/env bash
set -euo pipefail

project_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
base_path="${1:-/web/app/}"
if [[ ! "$base_path" =~ ^/[A-Za-z0-9_./-]*/$ || "$base_path" == *"//"* || "$base_path" == *"/../"* || "$base_path" == *"/./"* ]]; then
  echo 'Use a local absolute base path ending in /, e.g. /Intragram/web/app/.' >&2
  exit 1
fi
cd "$project_dir"
build_output="${BUILD_OUTPUT_DIR:-$project_dir/build/web-package}"
if [[ "$build_output" != /* ]]; then
  build_output="$project_dir/$build_output"
fi
if [[ "$build_output" == "$project_dir/build/web" ]]; then
  echo 'BUILD_OUTPUT_DIR must not be build/web (Flutter internal staging dir).' >&2
  exit 1
fi
destination="$project_dir/docs/web/app"
if [[ -e "$destination" && ! -f "$destination/.intragram-web-build" ]]; then
  echo 'Refusing to replace an unmarked docs/web/app directory.' >&2
  exit 1
fi

flutter build web --release --no-pub --no-web-resources-cdn --no-source-maps \
  --target lib/main_web.dart --base-href "$base_path" --output "$build_output"
test -f "$build_output/index.html"
test -f "$build_output/main.dart.js"
mkdir -p "$project_dir/build"
stage_dir="$(mktemp -d "$project_dir/docs/web/.app-stage.XXXXXX")"
backup_dir=''
restore_previous() {
  if [[ ! -d "$destination" && -n "$backup_dir" && -d "$backup_dir/app" ]]; then
    mv "$backup_dir/app" "$destination"
  fi
  if [[ -n "$stage_dir" && -d "$stage_dir" ]]; then
    local incomplete
    incomplete="$(mktemp -d "$project_dir/build/web-incomplete.XXXXXX")"
    mv "$stage_dir" "$incomplete/app"
  fi
}
trap restore_previous EXIT
cp -R "$build_output/." "$stage_dir/"
printf '%s\n' 'Generated by tool/build_web_app.sh from lib/main_web.dart.' > "$stage_dir/.intragram-web-build"
if [[ -d "$destination" ]]; then
  backup_dir="$(mktemp -d "$project_dir/build/web-previous.XXXXXX")"
  mv "$destination" "$backup_dir/app"
fi
mv "$stage_dir" "$destination"
stage_dir=''
echo "Built native Flutter UI for $base_path in docs/web/app. No deployment performed."
